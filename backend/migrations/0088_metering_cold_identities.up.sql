CREATE TABLE metering_cold_blocks (
 bloom VARBINARY(1024) NOT NULL,
 header_sha256 VARCHAR(64) NOT NULL,
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 node_id BIGINT UNSIGNED NOT NULL,
 kind TINYINT UNSIGNED NOT NULL,
 depth TINYINT UNSIGNED NOT NULL,
 prefix INT UNSIGNED NOT NULL,
 version TINYINT UNSIGNED NOT NULL,
 entry_count INT UNSIGNED NOT NULL,
 raw_bytes INT UNSIGNED NOT NULL,
 sha256 VARCHAR(64) NOT NULL,
 payload MEDIUMBLOB NOT NULL,
 UNIQUE KEY uk_metering_cold_page(node_id,kind,depth,prefix)
) ENGINE=InnoDB;
CREATE TABLE metering_identity_profiles(kind TINYINT UNSIGNED NOT NULL PRIMARY KEY,collation VARCHAR(64) NOT NULL,pad_space BOOLEAN NOT NULL) ENGINE=InnoDB;
CREATE TABLE metering_cold_progress(held_count BIGINT UNSIGNED NOT NULL DEFAULT 0,last_held_node_id BIGINT UNSIGNED NOT NULL DEFAULT 0,last_hold_reason VARCHAR(255) NOT NULL DEFAULT '',kind TINYINT UNSIGNED NOT NULL PRIMARY KEY,node_id BIGINT UNSIGNED NOT NULL,after_key VARCHAR(191) NOT NULL,after_id BIGINT UNSIGNED NOT NULL,next_pass_at DATETIME(3) NOT NULL) ENGINE=InnoDB;
CREATE TABLE metering_cold_roots(node_id BIGINT UNSIGNED NOT NULL,kind TINYINT UNSIGNED NOT NULL,page_count BIGINT NOT NULL,entry_count BIGINT NOT NULL,PRIMARY KEY(node_id,kind)) ENGINE=InnoDB;
