func TestBusinessTemplateRejectsForeignKeyCycles(t *testing.T) {
	for _, graph := range []map[string]map[string]bool{
		{"a": {"b": true}, "b": {"a": true}},
		{"self": {"self": true}},
		{"child": {"missing": true}},
	} {
		if _, err := businessTableOrder(graph); err == nil {
			t.Fatal("FK cycle accepted")
		}
	}
	order, err := businessTableOrder(map[string]map[string]bool{"child": {"parent": true}, "parent": {}})
	if err != nil || !reflect.DeepEqual(order, []string{"parent", "child"}) {
		t.Fatal("parent order wrong", order, err)
	}
}
