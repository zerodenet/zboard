func TestMySQLBusinessTemplatePreservesCompleteSchemaSeedsAndIsolation(t *testing.T) {
	cfg := mysqlBusinessConfig(t)
	template, err := mysqlBusinessTemplate(cfg)
	if err != nil {
		t.Fatal(err)
	}
	a, b := businessDatabaseForTest(t, cfg), businessDatabaseForTest(t, cfg)
	if a.Schema == b.Schema {
		t.Fatal("business fixtures share a schema")
	}
	for _, target := range []mysqlBusinessDatabase{a, b} {
		if err := template.install(target.DB); err != nil {
			t.Fatal(err)
		}
		actual, err := captureMySQLBusinessSnapshot(target.DB)
		if err != nil {
			t.Fatal(err)
		}
		if !businessSnapshotsEqual(actual, template) {
			t.Fatal("clone differs in complete SHOW CREATE/seeds/AUTO_INCREMENT/settings/trigger inventory", businessSnapshotDifference(actual, template))
		}
	}
	// An independent fresh database runs the original handler fixture's exact
	// seven steps and is captured at the same boundary, BEFORE constructing
	// services. The original newMySQLPublishHandlers remains unchanged.
	original := businessDatabaseForTest(t, cfg)
	for _, prepare := range []func(*gorm.DB) error{
		datastore.RunMigrations, datastore.ReconcileCommerceSchema, datastore.ReconcileSubscriptionAccessSchema,
		datastore.ReconcileZeroEventSchema, datastore.ReconcileTrafficReadSchema,
		datastore.ReconcileOperationsSchema, datastore.ReconcileFairUseTelemetrySchema,
	} {
		if err := prepare(original.DB); err != nil {
			t.Fatal(err)
		}
	}
	prepared, err := captureMySQLBusinessSnapshot(original.DB)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(businessWithoutSeedClocks(businessComparableSnapshot(prepared)), businessWithoutSeedClocks(businessComparableSnapshot(template))) {
		t.Fatal("business template differs from original real preparation (only generated seed clocks may differ)")
	}
	if len(template.Triggers) != 0 {
		t.Fatal("current migration left a legacy/double-writer trigger")
	}
	seeds := map[string]int{}
	for _, table := range template.Tables {
		if businessSeedTables[table.Name] {
			seeds[table.Name] = len(table.Rows)
		}
	}
	for table := range businessSeedTables {
		if seeds[table] == 0 {
			t.Fatal("missing actual initialization seed", table)
		}
	}
	// IDs and counters are target-local. Neither DML nor DDL mutation in A may
	// change B or the in-memory snapshot used for subsequent invocations.
	if err := a.DB.Create(&model.User{ID: 1, Email: "isolated@example.test", Password: "unused", Status: userStatusActive}).Error; err != nil {
		t.Fatal(err)
	}
	if err := a.DB.Exec("ALTER TABLE users ADD COLUMN fixture_only_probe INTEGER NOT NULL DEFAULT 0").Error; err != nil {
		t.Fatal(err)
	}
	untouched, err := captureMySQLBusinessSnapshot(b.DB)
	if err != nil {
		t.Fatal(err)
	}
	if !businessSnapshotsEqual(untouched, template) {
		t.Fatal("another fixture changed when A mutated")
	}
	c := businessDatabaseForTest(t, cfg)
	if err := template.install(c.DB); err != nil {
		t.Fatal(err)
	}
	later, err := captureMySQLBusinessSnapshot(c.DB)
	if err != nil || !businessSnapshotsEqual(later, template) {
		t.Fatal("cached template mutated after fixture use", err)
	}
	// A real collation change must remain unequal; redundant charset syntax
	// normalization cannot hide physical column semantics.
	if err := c.DB.Exec("ALTER TABLE fair_use_node_coverage MODIFY COLUMN core_instance_id varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL DEFAULT ''").Error; err != nil {
		t.Fatal(err)
	}
	changed, err := captureMySQLBusinessSnapshot(c.DB)
	if err != nil || businessSnapshotsEqual(changed, template) {
		t.Fatal("physical collation change hidden by DDL normalization", err)
	}
	if _, err := captureMySQLBusinessSnapshot(a.DB); err == nil {
		t.Fatal("business-populated database accepted as an initialization template")
	}
}

// Preserve every seed field byte/value. Only clocks GENERATED by separate real
// preparations differ. Clone-vs-template comparison above masks nothing,
// including schema_migrations.applied_at and every AUTO_INCREMENT option.
func businessWithoutSeedClocks(source *mysqlBusinessSnapshot) *mysqlBusinessSnapshot {
	out := *source
	out.Tables = append([]mysqlBusinessTable(nil), source.Tables...)
	for i, table := range out.Tables {
		out.Tables[i].Rows = make([][]any, len(table.Rows))
		for j, row := range table.Rows {
			copy := append([]any(nil), row...)
			for k, column := range table.Columns {
				generated := table.Name == "schema_migrations" && column == "applied_at"
				generated = generated || ((table.Name == "system_configs" || table.Name == "email_templates" || table.Name == "subscription_templates" || table.Name == "principal_statistics_state" || table.Name == "flow_start_statistics_state") && (column == "created_at" || column == "updated_at"))
				if generated {
					copy[k] = "generated-by-this-preparation"
				}
			}
			out.Tables[i].Rows[j] = copy
		}
	}
	return &out
}
func TestMySQLBusinessTemplateEnforcesForeignKeysAndChecks(t *testing.T) {
	cfg := mysqlBusinessConfig(t)
	template, err := mysqlBusinessTemplate(cfg)
	if err != nil {
		t.Fatal(err)
	}
	target := businessDatabaseForTest(t, cfg)
	if err := template.install(target.DB); err != nil {
		t.Fatal(err)
	}
	statement := "INSERT INTO wallet_accounts(user_id,currency,balance_minor,reserved_minor,revision,created_at,updated_at) VALUES (?,'CNY',?,0,1,UTC_TIMESTAMP(3),UTC_TIMESTAMP(3))"
	err = target.DB.Exec(statement, 99123, 0).Error
	var mysqlErr *mysqlconfig.MySQLError
	if !errors.As(err, &mysqlErr) || mysqlErr.Number != 1452 {
		t.Fatal("missing FK accepted an orphan or failed for another reason", err)
	}
	user := model.User{ID: 1, Email: "fk-parent@example.test", Password: "unused", Status: userStatusActive}
	if err := target.DB.Create(&user).Error; err != nil {
		t.Fatal(err)
	}
	err = target.DB.Exec(statement, user.ID, -1).Error
	if !errors.As(err, &mysqlErr) || mysqlErr.Number != 3819 {
		t.Fatal("CHECK constraint did not reject invalid balance", err)
	}
	if err := target.DB.Exec(statement, user.ID, 0).Error; err != nil {
		t.Fatal(err)
	}
	err = target.DB.Unscoped().Delete(&user).Error
	if !errors.As(err, &mysqlErr) || mysqlErr.Number != 1451 {
		t.Fatal("ON DELETE RESTRICT changed", err)
	}
	// The actual baseline has protocol_endpoints.parent_protocol_id -> itself.
	// Empty self tables preserve that FK in complete CREATE, never by disabling
	// checks or deleting the constraint to force a topological order.
	selfSeen := false
	for _, table := range template.Tables {
		if table.Name == "protocol_endpoints" {
			selfSeen = table.SelfReference && len(table.Rows) == 0
		}
	}
	if !selfSeen {
		t.Fatal("actual empty self-reference was not retained")
	}
	node := model.Node{Name: "business-self-fk", Config: "{}", IsEnabled: true}
	if err := target.DB.Create(&node).Error; err != nil {
		t.Fatal(err)
	}
	missingParent := uint(99123)
	endpoint := model.ProtocolEndpoint{NodeID: node.ID, Name: "self-fk-probe", RuntimeKey: "business-self-fk-probe", Protocol: "vless", Address: "example.test", Port: 443, PublicPort: 443, ParentProtocolID: &missingParent, ServerConfig: "{}", EgressConfig: "{}", ClientConfig: "{}", OptionalConfig: "{}", Tags: "[]"}
	err = target.DB.Create(&endpoint).Error
	if !errors.As(err, &mysqlErr) || mysqlErr.Number != 1452 {
		t.Fatal("self-referencing FK did not reject missing parent", err)
	}
	endpoint.ID, endpoint.ParentProtocolID = 0, nil
	if err := target.DB.Create(&endpoint).Error; err != nil {
		t.Fatal("empty parent must permit first endpoint", err)
	}
	child := endpoint
	child.ID = 0
	child.Name = "self-fk-child"
	child.RuntimeKey = "business-self-fk-child"
	child.ParentProtocolID = &endpoint.ID
	if err := target.DB.Create(&child).Error; err != nil {
		t.Fatal("existing parent must permit child", err)
	}
	// This probes the physical database FK, independently of protocol lifecycle deletion.
	if err := target.DB.Unscoped().Delete(&endpoint).Error; err != nil {
		t.Fatal(err)
	}
	if err := target.DB.First(&child, child.ID).Error; err != nil || child.ParentProtocolID != nil {
		t.Fatal("self FK ON DELETE SET NULL changed", err)
	}
	settings, err := businessSettings(target.DB)
	if err != nil || settings != template.Settings {
		t.Fatal("constraint/session settings changed", err)
	}
}
func TestMySQLBusinessTemplatePartialInstallDoesNotModifyOtherSchema(t *testing.T) {
	cfg := mysqlBusinessConfig(t)
	template, err := mysqlBusinessTemplate(cfg)
	if err != nil {
		t.Fatal(err)
	}
	target, err := openMySQLBusinessDatabase(cfg)
	if err != nil {
		t.Fatal(err)
	}
	open := true
	defer func() {
		if open {
			if err := target.close(); err != nil {
				t.Error(err)
			}
		}
	}()
	altered := *template
	altered.Tables = append([]mysqlBusinessTable(nil), template.Tables...)
	for i, table := range altered.Tables {
		if table.SelfReference {
			altered.Tables[i].Rows = [][]any{{"unsupported populated self seed"}}
			if err := altered.install(target.DB); err == nil {
				t.Fatal("populated self seed accepted without row-order proof")
			}
			var tables int64
			if err := target.DB.Raw("SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE()").Scan(&tables).Error; err != nil || tables != 0 {
				t.Fatal("self-seed refusal happened after writes", err)
			}
			altered.Tables[i].Rows = table.Rows
			break
		}
	}
	if len(altered.Tables) < 2 {
		t.Fatal("fixture lacks multiple tables")
	}
	altered.Tables[1].DDL = "CREATE TABLE fixture_bad_syntax ("
	if err := altered.install(target.DB); err == nil {
		t.Fatal("partial install error ignored")
	}
	// The failed database is not cached/reused; cleanup removes exactly its own
	// partially created objects. No fallback or automatic retry hides the error.
	open = false
	if err := target.close(); err != nil {
		t.Fatal(err)
	}
	adminCfg := cfg.Clone()
	adminCfg.DBName = ""
	// A fresh regular clone remains complete after the failed target is removed.
	good := businessDatabaseForTest(t, adminCfg)
	if err := template.install(good.DB); err != nil {
		t.Fatal(err)
	}
	actual, err := captureMySQLBusinessSnapshot(good.DB)
	if err != nil || !businessSnapshotsEqual(actual, template) {
		t.Fatal("partial failure changed immutable template", err, businessSnapshotDifference(actual, template))
	}
	var count int64
	if err := good.DB.Raw("SELECT COUNT(*) FROM information_schema.SCHEMATA WHERE SCHEMA_NAME = ?", target.Schema).Scan(&count).Error; err != nil || count != 0 {
		t.Fatal("partial-install schema leaked", err)
	}
}

func businessSnapshotsEqual(a, b *mysqlBusinessSnapshot) bool {
	return reflect.DeepEqual(businessComparableSnapshot(a), businessComparableSnapshot(b))
}

func businessSnapshotDifference(actual, expected *mysqlBusinessSnapshot) string {
	actual, expected = businessComparableSnapshot(actual), businessComparableSnapshot(expected)
	if actual == nil || expected == nil {
		return "nil snapshot"
	}
	if actual.Settings != expected.Settings {
		return "server/session/database settings differ"
	}
	if len(actual.Tables) != len(expected.Tables) {
		return fmt.Sprintf("table counts %d/%d", len(actual.Tables), len(expected.Tables))
	}
	for i, a := range actual.Tables {
		e := expected.Tables[i]
		if a.Name != e.Name {
			return fmt.Sprintf("table order %s/%s", a.Name, e.Name)
		}
		if a.DDL != e.DDL {
			return fmt.Sprintf("%s DDL actual=%q expected=%q", a.Name, a.DDL, e.DDL)
		}
		if !reflect.DeepEqual(a.Columns, e.Columns) {
			return a.Name + " column inventory differs"
		}
		if a.SelfReference != e.SelfReference {
			return a.Name + " self-reference classification differs"
		}
		if len(a.Rows) != len(e.Rows) {
			return fmt.Sprintf("%s row counts %d/%d", a.Name, len(a.Rows), len(e.Rows))
		}
		for j, row := range a.Rows {
			if len(row) != len(e.Rows[j]) {
				return a.Name + " row column count differs"
			}
			for k, v := range row {
				if !reflect.DeepEqual(v, e.Rows[j][k]) {
					x, _ := json.Marshal(v)
					y, _ := json.Marshal(e.Rows[j][k])
					return fmt.Sprintf("%s row%d column%s actual_type=%T expected_type=%T serialized_equal=%t hashes=%x/%x", a.Name, j, a.Columns[k], v, e.Rows[j][k], string(x) == string(y), sha256.Sum256(x), sha256.Sum256(y))
				}
			}
		}
	}
	return "only snapshot slice representation/trigger inventory differs"
}
