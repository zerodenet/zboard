import { flushPromises, mount } from '@vue/test-utils'
import { defineComponent, onMounted } from 'vue'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import CheckoutPayment from './CheckoutPayment.vue'
const mocks = vi.hoisted(() => ({ slots: vi.fn(), action: vi.fn(), context: vi.fn(), order: vi.fn() }))
vi.mock('../api/plugins', () => ({ fetchPluginSlots: mocks.slots }))
vi.mock('../api/client', () => ({ fetchAccountOrder: mocks.order }))
const slot = (id: string) => ({ plugin_id: id, generation: 1, slot: { id: 'checkout', slot: 'account.checkout.payment', title: id, surface: 'account', entrypoint: 'ui/pay.html' } })
const Frame = defineComponent({
  props: ['pluginId'], emits: ['checkoutOptions', 'checkoutStatus', 'unavailable'],
  setup(props, { emit, expose }) {
    expose({ checkoutAction: mocks.action, checkoutContext: mocks.context })
    onMounted(() => emit('checkoutOptions', [{ id: 'option', title: `Pay ${props.pluginId}`, prepare_action: 'pay.prepare', reconcile_action: 'pay.reconcile', disabled: props.pluginId === 'unavailable' }]))
    return () => null
  },
})
const Modal = defineComponent({ props: ['open', 'title'], emits: ['close'], template: '<section v-if="open" role="dialog"><h2>{{ title }}</h2><slot/><slot name="footer"/></section>' })
const open = (props = {}) => mount(CheckoutPayment, { props: { name: 'account.checkout.payment', currency: 'CNY', ...props }, global: { stubs: { PluginFrame: Frame, ModalDialog: Modal } } })
describe('payment contributions', () => {
  it('hands a new order to funding selection without loading or preparing any channel', async () => {
    const create = vi.fn().mockResolvedValue(71)
    const wrapper = open({ handoffToFunding: true, actorId: 1, createOrder: create }); await flushPromises()
    expect(mocks.slots).not.toHaveBeenCalled()
    expect(mocks.action).not.toHaveBeenCalled()
    expect(create).not.toHaveBeenCalled()
    await wrapper.findAll('button').find(button => button.text() === '创建订单并选择付款方式')!.trigger('click'); await flushPromises()
    expect(create).toHaveBeenCalledOnce()
    expect(wrapper.emitted('created')).toEqual([[71]])
    expect(mocks.action).not.toHaveBeenCalled()
    await wrapper.findAll('button').find(button => button.text() === '继续选择付款方式')!.trigger('click'); await flushPromises()
    expect(create).toHaveBeenCalledOnce()
    wrapper.unmount()
  })
  it('discards an old-account handoff result and never creates automatically after identity changes', async () => {
    let finish!: (id: number) => void
    const create = vi.fn(() => new Promise<number>(resolve => { finish = resolve }))
    const wrapper = open({ handoffToFunding: true, actorId: 1, createOrder: create }); await flushPromises()
    await wrapper.findAll('button').find(button => button.text() === '创建订单并选择付款方式')!.trigger('click')
    await wrapper.setProps({ actorId: 2 }); await flushPromises()
    finish(71); await flushPromises()
    expect(wrapper.emitted('created')).toBeUndefined()
    expect(create).toHaveBeenCalledOnce()
    expect(mocks.action).not.toHaveBeenCalled()
    wrapper.unmount()
  })
  it('opens payment confirmation from a specific order detail only on user action', async () => {
    const wrapper = open({ orderId: 27, openOnLoad: false }); await flushPromises()
    expect(wrapper.find('[role="dialog"]').exists()).toBe(false)
    await wrapper.findAll('button').find(button => button.text() === '查看支付状态')!.trigger('click'); await flushPromises()
    expect(wrapper.get('[role="dialog"]').text()).toContain('订单 #27')
    wrapper.unmount()
  })
  it.each([true, false])('closes the reserved window and respects public retryable=%s without success navigation', async retryable => {
    const create = vi.fn().mockResolvedValue(65)
    const popup = { closed: false, opener: null, close: vi.fn(), location: { replace: vi.fn() } }
    vi.spyOn(window, 'open').mockReturnValue(popup as any)
    mocks.action.mockRejectedValueOnce({ response: { status: 422, data: { code: 422, message: '<img src=x onerror=alert(1)> Operation rejected.', error: { version: 1, code: 'plugin_action_rejected', source: 'plugin', plugin_code: 'operation_closed', retryable } } } })
    const wrapper = open({ createOrder: create }); await flushPromises()
    await wrapper.findAll('button').find(b => b.text() === '确认并支付')!.trigger('click'); await flushPromises()
    const dialog = wrapper.get('[role="dialog"]')
    expect(dialog.text()).toContain('<img src=x onerror=alert(1)> Operation rejected.')
    expect(dialog.find('img').exists()).toBe(false)
    expect(popup.close).toHaveBeenCalledOnce()
    expect(popup.location.replace).not.toHaveBeenCalled()
    expect(wrapper.emitted('paid')).toBeUndefined()
    const retry = dialog.findAll('button').find(b => b.text() === '继续支付')!
    expect(retry.attributes('disabled') !== undefined).toBe(!retryable)
    await retry.trigger('click'); await flushPromises()
    expect(create).toHaveBeenCalledOnce()
    expect(mocks.action).toHaveBeenCalledTimes(retryable ? 2 : 1)
    wrapper.unmount(); vi.restoreAllMocks()
  })
  it('can read host settlement without replaying a non-retryable reconciliation action', async () => {
    const wrapper = open({ orderId: 66 }); await flushPromises()
    mocks.action.mockRejectedValueOnce({ response: { status: 422, data: { code: 422, message: 'Operation closed.', error: { version: 1, code: 'plugin_action_rejected', source: 'plugin', plugin_code: 'operation_closed', retryable: false } } } })
    await wrapper.findAll('button').find(b => b.text() === '已支付，确认')!.trigger('click'); await flushPromises()
    expect(wrapper.text()).toContain('Operation closed.')
    await wrapper.findAll('button').find(b => b.text() === '刷新订单状态')!.trigger('click'); await flushPromises()
    expect(mocks.action).toHaveBeenCalledOnce()
    mocks.order.mockResolvedValue({ id: 66, status: 'paid', payable_amount: 100, currency: 'CNY' })
    await wrapper.findAll('button').find(b => b.text() === '刷新订单状态')!.trigger('click'); await flushPromises()
    expect(wrapper.emitted('paid')).toEqual([[66]])
    expect(mocks.action).toHaveBeenCalledOnce()
    wrapper.unmount()
  })
  beforeEach(() => {
    vi.clearAllMocks()
    localStorage.clear()
    mocks.slots.mockResolvedValue([slot('plugin.one'), slot('plugin.two')])
    mocks.action.mockResolvedValue({ checkout_url: 'https://cashier.example/pay', status: 'paid' })
    mocks.context.mockResolvedValue({ status: 'pending' })
    mocks.order.mockImplementation(async id => ({ id, status: 'pending', payable_amount: 100, currency: 'CNY' }))
  })
  it('discovers multiple plugins asynchronously and retries discovery locally', async () => {
    mocks.slots.mockRejectedValueOnce(new Error('offline'))
    const wrapper = open()
    await flushPromises()
    expect(wrapper.text()).toContain('支付方式加载失败')
    await wrapper.findAll('button')[0].trigger('click'); await flushPromises()
    expect(wrapper.findAll('input[type=radio]')).toHaveLength(2)
    expect(wrapper.text()).toContain('plugin.one')
    expect(wrapper.text()).toContain('plugin.two')
    wrapper.unmount()
  })
  it('rejects unavailable options and coalesces clicks while keeping the same order for retries', async () => {
    let done!: (order: number) => void
    const create = vi.fn(() => new Promise<number>(resolve => { done = resolve }))
    const popup = { closed: false, opener: null, close: vi.fn(), location: { replace: vi.fn() } }
    vi.spyOn(window, 'open').mockReturnValue(popup as any)
    const wrapper = open({ createOrder: create })
    await flushPromises()
    const pay = wrapper.findAll('button').find(button => button.text() === '确认并支付')!
    await pay.trigger('click'); await pay.trigger('click')
    expect(create).toHaveBeenCalledOnce()
    expect(window.open).toHaveBeenCalledTimes(1)
    done(19); await flushPromises()
    expect(mocks.action).toHaveBeenCalledWith(19, 'pay.prepare', { option_id: 'option' })
    await wrapper.findAll('button').find(button => button.text() === '重新打开支付窗口')!.trigger('click'); await flushPromises()
    expect(create).toHaveBeenCalledOnce()
    expect(mocks.action).toHaveBeenLastCalledWith(19, 'pay.prepare', { option_id: 'option' })
    wrapper.unmount(); vi.restoreAllMocks()
    mocks.slots.mockResolvedValue([slot('unavailable')])
    const unavailable = open({ orderId: 19 }); await flushPromises()
    expect(unavailable.find('input').attributes('disabled')).toBeDefined()
    expect(unavailable.findAll('button').find(button => button.text() === '继续支付')!.attributes('disabled')).toBeDefined()
    unavailable.unmount()
  })
  it('shows one host retry with a structured provider error and never offers order-only creation', async () => {
    const createOnly = vi.fn()
    const wrapper = open({ createOnly })
    await flushPromises()
    wrapper.findAllComponents(Frame)[0].vm.$emit('checkoutStatus', { state: 'error', code: 'deadline_exceeded' })
    await flushPromises()
    expect(wrapper.text()).toContain('支付方式加载超时')
    wrapper.findAllComponents(Frame)[0].vm.$emit('checkoutStatus', { state: 'error', code: 'provider_metadata_missing' })
    await flushPromises()
    expect(wrapper.text()).toContain('收款信息尚未就绪')
    expect(wrapper.text()).not.toContain('确认创建订单')
    expect(wrapper.findAll('button').filter(b => b.text() === '重新加载支付方式')).toHaveLength(1)
    expect(wrapper.text()).toContain('Pay plugin.two')
    expect(createOnly).not.toHaveBeenCalled()
    wrapper.unmount()
  })
  it('times out an unresponsive contribution without creating an order', async () => {
    vi.useFakeTimers()
    const create = vi.fn()
    const Silent = defineComponent({ setup() { return () => null } })
    const wrapper = mount(CheckoutPayment, { props: { name: 'account.checkout.payment', currency: 'CNY', createOrder: create }, global: { stubs: { PluginFrame: Silent, ModalDialog: Modal } } })
    await flushPromises()
    await vi.advanceTimersByTimeAsync(35_000)
    expect(wrapper.text()).toContain('支付方式加载超时')
    expect(wrapper.findAll('button').find(b => b.text() === '确认并支付')!.attributes('disabled')).toBeDefined()
    expect(create).not.toHaveBeenCalled()
    wrapper.unmount(); vi.useRealTimers()
  })
  it('return reconciliation uses the owning plugin and only host order status proves success', async () => {
    const wrapper = open({ name: 'account.orders.payment', orderId: 33, preferredPlugin: 'plugin.two', reconcileOnLoad: true })
    await flushPromises()
    expect(mocks.action).toHaveBeenCalledWith(33, 'pay.reconcile', { option_id: 'option' })
    expect(wrapper.emitted('paid')).toBeUndefined()
    expect(wrapper.text()).toContain('尚未确认到账')
    mocks.order.mockImplementation(async id => ({ id, status: 'paid', payable_amount: 100, currency: 'CNY' }))
    await wrapper.findAll('button').find(button => button.text() === '已支付，确认')!.trigger('click'); await flushPromises()
    expect(wrapper.emitted('paid')).toEqual([[33]])
    wrapper.unmount()
  })
  it('restores the payment method for an existing order without creating a new order', async () => {
    localStorage.setItem('zboard-payment-choice:44', JSON.stringify({ plugin: 'plugin.two', option: 'option' }))
    const create = vi.fn()
    const popup = { closed: false, opener: null, close: vi.fn(), location: { replace: vi.fn() } }
    vi.spyOn(window, 'open').mockReturnValue(popup as any)
    const wrapper = open({ orderId: 44, createOrder: create }); await flushPromises()
    expect(wrapper.findAll('input')[1].element.checked).toBe(true)
    await wrapper.findAll('button').find(button => button.text() === '继续支付')!.trigger('click'); await flushPromises()
    expect(create).not.toHaveBeenCalled()
    expect(mocks.action).toHaveBeenCalledWith(44, 'pay.prepare', { option_id: 'option' })
    expect(popup.location.replace).toHaveBeenCalledWith('https://cashier.example/pay')
    wrapper.unmount(); vi.restoreAllMocks()
  })
  it('discards a pending preparation when the user switches orders and closes its blank window', async () => {
    let context!: (value: any) => void
    const popup = { closed: false, opener: null, close: vi.fn(), location: { replace: vi.fn() } }
    vi.spyOn(window, 'open').mockReturnValue(popup as any)
    const wrapper = open({ orderId: 44 }); await flushPromises()
    mocks.order.mockImplementationOnce(() => new Promise(resolve => { context = resolve }))
    await wrapper.findAll('button').find(button => button.text() === '继续支付')!.trigger('click')
    await wrapper.setProps({ orderId: 45 }); await flushPromises()
    context({ status: 'paid' }); await flushPromises()
    expect(mocks.action).not.toHaveBeenCalled()
    expect(wrapper.emitted('paid')).toBeUndefined()
    expect(wrapper.text()).toContain('订单 #45')
    expect(popup.close).toHaveBeenCalledOnce()
    expect(popup.location.replace).not.toHaveBeenCalled()
    wrapper.unmount(); vi.restoreAllMocks()
  })
  it('reads host settlement after a lost plugin response instead of displaying a payment failure', async () => {
    const wrapper = open({ orderId: 51 }); await flushPromises()
    mocks.action.mockImplementationOnce(async () => {
      mocks.order.mockImplementation(async id => ({ id, status: 'paid', payable_amount: 100, currency: 'CNY' }))
      throw new Error('response lost')
    })
    await wrapper.findAll('button').find(button => button.text() === '已支付，确认')!.trigger('click'); await flushPromises()
    expect(wrapper.emitted('paid')).toEqual([[51]])
    expect(wrapper.text()).toContain('ZBoard 已确认订单完成')
    expect(wrapper.text()).not.toContain('response lost')
    wrapper.unmount()
  })
  it('can confirm a host receipt after all payment contributions are unavailable', async () => {
    mocks.slots.mockResolvedValue([])
    const wrapper = open({ orderId: 52 }); await flushPromises()
    mocks.order.mockImplementation(async id => ({ id, status: 'paid', payable_amount: 100, currency: 'CNY' }))
    await wrapper.findAll('button').find(button => button.text() === '已支付，确认')!.trigger('click'); await flushPromises()
    expect(mocks.action).not.toHaveBeenCalled()
    expect(wrapper.emitted('paid')).toEqual([[52]])
    wrapper.unmount()
  })
  it('keeps the saved disabled method available for historical reconciliation only', async () => {
    localStorage.setItem('zboard-payment-choice:53', JSON.stringify({ plugin: 'unavailable', option: 'option' }))
    mocks.slots.mockResolvedValue([slot('unavailable')])
    const wrapper = open({ orderId: 53 }); await flushPromises()
    const pay = wrapper.findAll('button').find(button => button.text() === '继续支付')!
    expect(pay.attributes('disabled')).toBeDefined()
    await pay.trigger('click'); expect(mocks.action).not.toHaveBeenCalled()
    await wrapper.findAll('button').find(button => button.text() === '已支付，确认')!.trigger('click'); await flushPromises()
    expect(mocks.action).toHaveBeenCalledWith(53, 'pay.reconcile', { option_id: 'option' })
    expect(wrapper.emitted('paid')).toBeUndefined()
    wrapper.unmount()
  })
  it('does not accept a claimed paid response when the host read fails', async () => {
    const wrapper = open({ orderId: 54 }); await flushPromises()
    mocks.action.mockImplementationOnce(async () => { mocks.order.mockRejectedValue(new Error('host offline')); return { status: 'paid' } })
    await wrapper.findAll('button').find(button => button.text() === '已支付，确认')!.trigger('click'); await flushPromises()
    expect(wrapper.emitted('paid')).toBeUndefined()
    expect(wrapper.text()).toContain('host offline')
    wrapper.unmount()
  })
  it('will not open payment for a canceled host order', async () => {
    mocks.order.mockImplementation(async id => ({ id, status: 'canceled', payable_amount: 100, currency: 'CNY' }))
    const popup = vi.spyOn(window, 'open')
    const wrapper = open({ orderId: 55 }); await flushPromises()
    expect(wrapper.findAll('button').some(button => button.text() === '继续支付')).toBe(false)
    expect(wrapper.get('[role="dialog"]').text()).toContain('订单已取消')
    expect(popup).not.toHaveBeenCalled()
    expect(mocks.action).not.toHaveBeenCalled()
    wrapper.unmount(); vi.restoreAllMocks()
  })
  it('keeps waiting, amount and settlement confirmation in a dismissible dialog', async () => {
    const create = vi.fn().mockResolvedValue(61)
    const popup = { closed: false, opener: null, close: vi.fn(), location: { replace: vi.fn() } }
    vi.spyOn(window, 'open').mockReturnValue(popup as any)
    const wrapper = open({ createOrder: create, embedded: true }); await flushPromises()
    expect(wrapper.find('[role="dialog"]').exists()).toBe(false)
    await wrapper.findAll('button').find(b => b.text() === '确认并支付')!.trigger('click'); await flushPromises()
    const dialog = wrapper.get('[role="dialog"]')
    expect(dialog.text()).toContain('订单 #61')
    expect(dialog.text()).toContain('等待付款')
    expect(dialog.text()).toContain('订单应付')
    expect(dialog.text()).toContain('已支付，确认')
    expect(wrapper.get('.checkout-payment__actions').text()).toBe('查看支付状态')
    await dialog.findAll('button').find(b => b.text() === '稍后处理')!.trigger('click')
    expect(wrapper.find('[role="dialog"]').exists()).toBe(false)
    expect(wrapper.text()).not.toContain('等待付款')
    expect(wrapper.text()).not.toContain('已支付，确认')
    expect(popup.close).not.toHaveBeenCalled()
    await wrapper.findAll('button').find(b => b.text() === '查看支付状态')!.trigger('click')
    expect(wrapper.get('[role="dialog"]').text()).toContain('订单 #61')
    expect(create).toHaveBeenCalledOnce()
    expect(window.open).toHaveBeenCalledOnce()
    wrapper.unmount(); vi.restoreAllMocks()
  })
  it('does not reopen a dismissed dialog when asynchronous payment preparation finishes', async () => {
    let done!: (id: number) => void
    const create = vi.fn(() => new Promise<number>(resolve => { done = resolve }))
    const popup = { closed: false, opener: null, close: vi.fn(), location: { replace: vi.fn() } }
    vi.spyOn(window, 'open').mockReturnValue(popup as any)
    const wrapper = open({ createOrder: create }); await flushPromises()
    await wrapper.findAll('button').find(b => b.text() === '确认并支付')!.trigger('click')
    expect(window.open).toHaveBeenCalledOnce()
    await wrapper.get('[role="dialog"]').findAll('button').find(b => b.text() === '稍后处理')!.trigger('click')
    done(62); await flushPromises()
    expect(wrapper.find('[role="dialog"]').exists()).toBe(false)
    expect(popup.location.replace).toHaveBeenCalledWith('https://cashier.example/pay')
    await wrapper.findAll('button').find(b => b.text() === '查看支付状态')!.trigger('click')
    await wrapper.get('[role="dialog"]').findAll('button').find(b => b.text() === '重新打开支付窗口')!.trigger('click'); await flushPromises()
    expect(create).toHaveBeenCalledOnce()
    expect(mocks.action).toHaveBeenLastCalledWith(62, 'pay.prepare', { option_id: 'option' })
    wrapper.unmount(); vi.restoreAllMocks()
  })
  it('shows popup-blocking and preparation failures in the dialog without duplicating orders', async () => {
    const create = vi.fn().mockResolvedValue(63)
    const reserve = vi.spyOn(window, 'open').mockReturnValueOnce(null)
    const wrapper = open({ createOrder: create }); await flushPromises()
    await wrapper.findAll('button').find(b => b.text() === '确认并支付')!.trigger('click')
    expect(wrapper.get('[role="dialog"]').text()).toContain('请允许本站打开支付窗口')
    expect(create).not.toHaveBeenCalled()
    const popup = { closed: false, opener: null, close: vi.fn(), location: { replace: vi.fn() } }
    reserve.mockReturnValue(popup as any)
    mocks.action.mockRejectedValueOnce(new Error('prepare unavailable'))
    await wrapper.get('[role="dialog"]').findAll('button').find(b => b.text() === '确认并支付')!.trigger('click'); await flushPromises()
    expect(wrapper.get('[role="dialog"]').text()).toContain('prepare unavailable')
    expect(wrapper.get('[role="dialog"]').text()).toContain('订单 #63')
    await wrapper.get('[role="dialog"]').findAll('button').find(b => b.text() === '继续支付')!.trigger('click'); await flushPromises()
    expect(create).toHaveBeenCalledOnce()
    expect(mocks.action).toHaveBeenLastCalledWith(63, 'pay.prepare', { option_id: 'option' })
    wrapper.unmount(); vi.restoreAllMocks()
  })
  it('teleports the confirmation dialog outside the embedded payment card', async () => {
    const popup = { closed: false, opener: null, close: vi.fn(), location: { replace: vi.fn() } }
    vi.spyOn(window, 'open').mockReturnValue(popup as any)
    const wrapper = mount(CheckoutPayment, { attachTo: document.body, props: { name: 'account.checkout.payment', currency: 'CNY', createOrder: async () => 64, embedded: true }, global: { stubs: { PluginFrame: Frame } } })
    await flushPromises()
    await wrapper.findAll('button').find(b => b.text() === '确认并支付')!.trigger('click'); await flushPromises()
    const dialog = document.body.querySelector('[role="dialog"]')!
    expect(dialog.getAttribute('aria-modal')).toBe('true')
    expect(dialog.closest('.checkout-payment')).toBeNull()
    expect(dialog.textContent).toContain('订单 #64')
    expect(wrapper.get('.checkout-payment__actions').text()).toBe('查看支付状态')
    ;(dialog.querySelector('[aria-label="关闭弹窗"]') as HTMLButtonElement).click(); await flushPromises()
    expect(document.body.querySelector('[role="dialog"]')).toBeNull()
    expect(document.activeElement).toBe(wrapper.get('.checkout-payment__actions button').element)
    wrapper.unmount(); vi.restoreAllMocks()
  })
})
